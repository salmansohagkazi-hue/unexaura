import React, { useState, useEffect } from 'react';
import {
  testSupabaseConnection,
  ConnectionTestResult,
  SUPABASE_PROJECT_ID,
  SUPABASE_URL,
  SUPABASE_ANON_KEY
} from '../lib/supabase';
import {
  Database,
  CheckCircle2,
  AlertTriangle,
  RefreshCw,
  Copy,
  Check,
  ShieldCheck,
  Key,
  Globe,
  ExternalLink,
  Code2,
  Table,
  Lock
} from 'lucide-react';

export const SupabaseManager: React.FC = () => {
  const [testResult, setTestResult] = useState<ConnectionTestResult | null>(null);
  const [isLoading, setIsLoading] = useState<boolean>(false);
  const [copiedKey, setCopiedKey] = useState<string | null>(null);
  const [activeSchemaTab, setActiveSchemaTab] = useState<'orders' | 'products' | 'categories' | 'all'>('all');

  const runConnectionTest = async () => {
    setIsLoading(true);
    try {
      const res = await testSupabaseConnection();
      setTestResult(res);
    } catch (err: any) {
      setTestResult({
        success: false,
        message: err?.message || 'Connection failed',
        authHealthStatus: 0,
        projectId: SUPABASE_PROJECT_ID,
        timestamp: new Date().toISOString()
      });
    } finally {
      setIsLoading(false);
    }
  };

  useEffect(() => {
    runConnectionTest();
  }, []);

  const handleCopy = (text: string, label: string) => {
    navigator.clipboard.writeText(text);
    setCopiedKey(label);
    setTimeout(() => setCopiedKey(null), 2500);
  };

  const sqlSchema = `-- ====================================================================
-- UNEX AURA E-Commerce Database Schema for Supabase
-- Run this in Supabase Dashboard -> SQL Editor -> New Query
-- ====================================================================

-- 1. CATEGORIES TABLE
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    icon TEXT DEFAULT '🕌',
    image_url TEXT,
    sort_order INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. PRODUCTS TABLE
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    category_name TEXT,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    price NUMERIC(10, 2) NOT NULL,
    old_price NUMERIC(10, 2),
    weight_grams INT DEFAULT 1200,
    stock INT DEFAULT 15,
    badge TEXT,
    featured BOOLEAN DEFAULT false,
    image_url TEXT NOT NULL,
    material TEXT DEFAULT 'Surgical Stainless Steel',
    thickness TEXT DEFAULT '0.6 mm',
    size_dimensions TEXT DEFAULT '75cm × 40cm',
    description TEXT,
    bangla_short_desc TEXT,
    qualities JSONB DEFAULT '[]'::jsonb,
    sizes JSONB DEFAULT '[]'::jsonb,
    room_images JSONB DEFAULT '{}'::jsonb,
    rating NUMERIC(3, 2) DEFAULT 5.0,
    review_count INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. ORDERS TABLE
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT NOT NULL UNIQUE,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    user_name TEXT NOT NULL,
    user_email TEXT,
    user_phone TEXT NOT NULL,
    shipping_address TEXT NOT NULL,
    city TEXT NOT NULL,
    delivery_zone TEXT NOT NULL DEFAULT 'dhaka',
    total_weight_grams INT DEFAULT 0,
    delivery_charge NUMERIC(10, 2) DEFAULT 0,
    subtotal_amount NUMERIC(10, 2) NOT NULL,
    total_amount NUMERIC(10, 2) NOT NULL,
    payment_method TEXT DEFAULT 'cod',
    payment_status TEXT DEFAULT 'unpaid',
    status TEXT DEFAULT 'pending',
    order_notes TEXT,
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    tracking_number TEXT,
    courier_name TEXT,
    courier_phone TEXT,
    estimated_delivery TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. ENABLE ROW LEVEL SECURITY (RLS)
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- 5. RLS POLICIES FOR CATEGORIES
-- Anyone (anon and authenticated) can view categories
CREATE POLICY "Public read categories" 
ON public.categories FOR SELECT 
USING (true);

-- 6. RLS POLICIES FOR PRODUCTS
-- Anyone (anon and authenticated) can view active products
CREATE POLICY "Public read products" 
ON public.products FOR SELECT 
USING (true);

-- 7. RLS POLICIES FOR ORDERS
-- Customers (including guest anon users) can create orders
CREATE POLICY "Anyone can place order" 
ON public.orders FOR INSERT 
WITH CHECK (true);

-- Customers can view their own orders by order_number or user_id
CREATE POLICY "Customers can view their orders" 
ON public.orders FOR SELECT 
USING (auth.uid() = user_id OR user_id IS NULL);
`;

  return (
    <div className="space-y-6">
      {/* HEADER CARD */}
      <div className="bg-white p-6 rounded-3xl border border-slate-200/80 shadow-xs space-y-6">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-100 pb-5">
          <div className="flex items-center gap-3">
            <div className="w-12 h-12 rounded-2xl bg-emerald-500/10 text-emerald-600 flex items-center justify-center font-bold shadow-xs">
              <Database className="w-6 h-6" />
            </div>
            <div>
              <h3 className="text-lg font-black text-[#0f3d44] flex items-center gap-2">
                <span>Supabase Backend Integration</span>
                {testResult?.success ? (
                  <span className="text-xs bg-emerald-100 text-emerald-800 font-bold px-2.5 py-0.5 rounded-full flex items-center gap-1">
                    <CheckCircle2 className="w-3.5 h-3.5" />
                    <span>সংযুক্ত (Connected)</span>
                  </span>
                ) : (
                  <span className="text-xs bg-amber-100 text-amber-800 font-bold px-2.5 py-0.5 rounded-full flex items-center gap-1">
                    <AlertTriangle className="w-3.5 h-3.5" />
                    <span>কানেকশন চেক প্রয়োজন</span>
                  </span>
                )}
              </h3>
              <p className="text-xs text-slate-500 mt-0.5">
                PostgreSQL ডাটাবেজ, রিয়েল-টাইম অর্ডার স্টোরেজ এবং ক্লায়েন্ট-সাইড আরএলএস সিকিউরিটি
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2.5">
            <button
              type="button"
              onClick={runConnectionTest}
              disabled={isLoading}
              className="px-4 py-2.5 rounded-xl text-xs font-bold bg-slate-100 hover:bg-slate-200 text-slate-800 transition flex items-center gap-2 cursor-pointer disabled:opacity-50"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${isLoading ? 'animate-spin' : ''}`} />
              <span>{isLoading ? 'চেক হচ্ছে...' : 'Test Connection'}</span>
            </button>
            <a
              href={`https://supabase.com/dashboard/project/${SUPABASE_PROJECT_ID}`}
              target="_blank"
              rel="noreferrer"
              className="px-4 py-2.5 rounded-xl text-xs font-bold bg-emerald-600 hover:bg-emerald-700 text-white transition flex items-center gap-1.5 shadow-xs"
            >
              <span>Supabase Dashboard</span>
              <ExternalLink className="w-3.5 h-3.5" />
            </a>
          </div>
        </div>

        {/* CONNECTION STATUS & DIAGNOSTICS */}
        {testResult && (
          <div
            className={`p-4 rounded-2xl border text-xs space-y-3 ${
              testResult.success
                ? 'bg-emerald-50/70 border-emerald-200 text-emerald-950'
                : 'bg-rose-50 border-rose-200 text-rose-950'
            }`}
          >
            <div className="flex items-center justify-between">
              <div className="flex items-center gap-2 font-bold text-sm">
                {testResult.success ? (
                  <CheckCircle2 className="w-5 h-5 text-emerald-600 shrink-0" />
                ) : (
                  <AlertTriangle className="w-5 h-5 text-rose-600 shrink-0" />
                )}
                <span>{testResult.message}</span>
              </div>
              <span className="text-[11px] opacity-75 font-mono">
                {new Date(testResult.timestamp).toLocaleTimeString()}
              </span>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 pt-1">
              <div className="bg-white/80 p-2.5 rounded-xl border border-emerald-100/80">
                <span className="text-[10px] text-slate-500 uppercase font-bold block">Auth API Status</span>
                <span className="font-bold text-emerald-800 flex items-center gap-1 mt-0.5">
                  <span className="w-2 h-2 rounded-full bg-emerald-500"></span>
                  <span>HTTP {testResult.authHealthStatus} OK ({testResult.authVersion || 'GoTrue'})</span>
                </span>
              </div>

              <div className="bg-white/80 p-2.5 rounded-xl border border-emerald-100/80">
                <span className="text-[10px] text-slate-500 uppercase font-bold block">Security Standard</span>
                <span className="font-bold text-emerald-800 flex items-center gap-1 mt-0.5">
                  <ShieldCheck className="w-3.5 h-3.5 text-emerald-600" />
                  <span>Publishable Anon Key (Safe)</span>
                </span>
              </div>

              <div className="bg-white/80 p-2.5 rounded-xl border border-emerald-100/80">
                <span className="text-[10px] text-slate-500 uppercase font-bold block">PostgreSQL Tables</span>
                <span className="font-bold text-slate-800 mt-0.5 block">
                  {testResult.tablesFound && testResult.tablesFound.length > 0 ? (
                    <span className="text-emerald-700">{testResult.tablesFound.length} টি টেবিল প্রস্তুত</span>
                  ) : (
                    <span className="text-amber-700">টেবিলগুলো তৈরি করা বাকি</span>
                  )}
                </span>
              </div>
            </div>
          </div>
        )}

        {/* CREDENTIALS SECTION (SAFELY DISPLAYED) */}
        <div className="space-y-4">
          <h4 className="text-xs font-bold uppercase tracking-wider text-slate-500">
            বর্তমান Supabase ক্রেডেনশিয়ালস
          </h4>

          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {/* Project URL */}
            <div className="bg-slate-50 p-3.5 rounded-2xl border border-slate-200">
              <div className="flex items-center justify-between mb-1.5">
                <span className="text-[11px] font-bold text-slate-600 flex items-center gap-1.5">
                  <Globe className="w-3.5 h-3.5 text-emerald-600" />
                  <span>Supabase Project URL</span>
                </span>
                <button
                  type="button"
                  onClick={() => handleCopy(SUPABASE_URL, 'url')}
                  className="text-[11px] text-indigo-600 hover:text-indigo-800 font-bold flex items-center gap-1 cursor-pointer"
                >
                  {copiedKey === 'url' ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
                  <span>{copiedKey === 'url' ? 'কপি হয়েছে' : 'কপি করুন'}</span>
                </button>
              </div>
              <p className="font-mono text-xs text-[#0f3d44] font-bold truncate">
                {SUPABASE_URL}
              </p>
              <span className="text-[10px] text-slate-400 mt-1 block">
                Project Reference ID: <strong className="font-mono text-slate-600">{SUPABASE_PROJECT_ID}</strong>
              </span>
            </div>

            {/* Publishable Key */}
            <div className="bg-slate-50 p-3.5 rounded-2xl border border-slate-200">
              <div className="flex items-center justify-between mb-1.5">
                <span className="text-[11px] font-bold text-slate-600 flex items-center gap-1.5">
                  <Key className="w-3.5 h-3.5 text-amber-600" />
                  <span>Publishable API Key (Anon Key)</span>
                </span>
                <button
                  type="button"
                  onClick={() => handleCopy(SUPABASE_ANON_KEY, 'key')}
                  className="text-[11px] text-indigo-600 hover:text-indigo-800 font-bold flex items-center gap-1 cursor-pointer"
                >
                  {copiedKey === 'key' ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
                  <span>{copiedKey === 'key' ? 'কপি হয়েছে' : 'কপি করুন'}</span>
                </button>
              </div>
              <p className="font-mono text-xs text-[#0f3d44] font-bold truncate">
                {SUPABASE_ANON_KEY.slice(0, 20)}...{SUPABASE_ANON_KEY.slice(-10)}
              </p>
              <span className="text-[10px] text-emerald-600 font-semibold mt-1 flex items-center gap-1">
                <ShieldCheck className="w-3 h-3" />
                <span>নিরাপদ ক্লায়েন্ট কী — কোনো সিক্রেট বা service_role কী কোডে ব্যবহার করা হয়নি।</span>
              </span>
            </div>
          </div>
        </div>

        {/* SECURITY & RLS POLICIES NOTICE */}
        <div className="bg-gradient-to-r from-amber-50 to-orange-50 p-4 rounded-2xl border border-amber-200 text-xs text-amber-950 space-y-2">
          <div className="font-bold flex items-center gap-2 text-amber-900">
            <Lock className="w-4 h-4 text-amber-600 shrink-0" />
            <span>নিরাপত্তা ও RLS পলিসি গাইডলাইন</span>
          </div>
          <p className="leading-relaxed text-amber-900/90">
            আপনার নির্দেশনা অনুযায়ী বর্তমান ওয়েবসাইটের কোনো ডিজাইন, ফাংশনালিটি বা অর্ডার সিস্টেম পরিবর্তন করা হয়নি। ডাটাবেজে ডাটা সংরক্ষণ চালু করার আগে নিচের টেবিলগুলো Supabase Dashboard-এর <strong>SQL Editor</strong>-এ এক ক্লিকে রান করে তৈরি করে নিতে হবে।
          </p>
        </div>

        {/* SQL SCHEMA CODE BOX */}
        <div className="space-y-3">
          <div className="flex items-center justify-between">
            <h4 className="text-xs font-bold text-slate-800 flex items-center gap-2">
              <Code2 className="w-4 h-4 text-emerald-600" />
              <span>প্রয়োজনীয় টেবিল ও RLS পলিসি স্ক্রিপ্ট (SQL Script)</span>
            </h4>
            <button
              type="button"
              onClick={() => handleCopy(sqlSchema, 'schema')}
              className="px-3 py-1.5 rounded-lg text-xs font-bold bg-emerald-50 text-emerald-700 hover:bg-emerald-100 border border-emerald-200 flex items-center gap-1.5 cursor-pointer"
            >
              {copiedKey === 'schema' ? <Check className="w-3.5 h-3.5 text-emerald-700" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copiedKey === 'schema' ? 'সম্পূর্ণ SQL কপি হয়েছে!' : 'Copy SQL Schema'}</span>
            </button>
          </div>

          <div className="relative rounded-2xl overflow-hidden border border-slate-800 bg-slate-950 text-slate-200 p-4 font-mono text-[11px] max-h-96 overflow-y-auto">
            <pre className="whitespace-pre">{sqlSchema}</pre>
          </div>
          <p className="text-[11px] text-slate-500">
            💡 কীভাবে সেটআপ করবেন: Supabase ড্যাশবোর্ডে গিয়ে <strong>SQL Editor</strong> মেনুতে যান ➔ <strong>New Query</strong> চাপুন ➔ উপরের সম্পূর্ণ কোডটি পেস্ট করে <strong>Run</strong> বাটনে ক্লিক করুন।
          </p>
        </div>
      </div>
    </div>
  );
};
